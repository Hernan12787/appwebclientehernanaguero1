-- Tabla del mapa de contacto para el proyecto ytyjalgshnjfaqpckuxr
-- (el mismo proyecto que usa la función "Encuesta").
-- Ejecutar en Supabase -> SQL Editor.

create table if not exists public.supabasemap (
  id bigint generated by default as identity primary key,
  titulo text not null,
  direccion text,
  embed_url text,
  mapa_url text,
  created_at timestamptz not null default now()
);

alter table public.supabasemap enable row level security;

drop policy if exists "mapa_select_anon" on public.supabasemap;
create policy "mapa_select_anon"
on public.supabasemap
for select
to anon, authenticated
using (true);

