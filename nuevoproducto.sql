-- Tabla de productos nuevos para el proyecto.
-- Ejecutar en Supabase -> SQL Editor.

create table if not exists public.nuevoproducto (
  id bigint generated by default as identity primary key,
  nombre text not null,
  precio numeric not null default 0,
  url text,
  created_at timestamptz not null default now()
);

alter table public.nuevoproducto enable row level security;

drop policy if exists "nuevoproducto_select_anon" on public.nuevoproducto;
create policy "nuevoproducto_select_anon"
on public.nuevoproducto
for select
to anon, authenticated
using (true);

drop policy if exists "nuevoproducto_insert_anon" on public.nuevoproducto;
create policy "nuevoproducto_insert_anon"
on public.nuevoproducto
for insert
to anon, authenticated
with check (true);

drop policy if exists "nuevoproducto_update_anon" on public.nuevoproducto;
create policy "nuevoproducto_update_anon"
on public.nuevoproducto
for update
to anon, authenticated
using (true)
with check (true);
